/**
 * Package the unmodified Prism core/grammars as a self-contained worklet
 * factory. Worklets 0.7 cannot import ordinary libraries into its runtime;
 * functions CREATED inside a worklet are ordinary local JS and can call each
 * other. No manual eval, Prism patches, or global Bundle Mode required.
 *
 * Regenerate after editing syntax/tokenize.ts or engine/highlight.ts:
 *   pnpm --filter happy-app generate:diff-syntax
 */
const { buildSync } = require('esbuild');
const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'sources/components/diff/syntax/factory.generated.ts');
const result = buildSync({
    absWorkingDir: root,
    entryPoints: ['sources/components/diff/syntax/tokenize.ts'],
    bundle: true,
    format: 'iife',
    globalName: 'DiffSyntax',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    // Prism's DOM/worker feature detection must not become free identifiers
    // captured eagerly by the Worklets Babel plugin on Hermes.
    define: {
        window: 'undefined', document: 'undefined', self: 'undefined',
        Worker: 'undefined', WorkerGlobalScope: 'undefined', global: 'globalThis',
        Prism: 'globalThis.Prism',
    },
    legalComments: 'inline',
    write: false,
});
const license = readFileSync(require.resolve('prismjs/LICENSE'), 'utf8');
const code = `// Generated by scripts/build-diff-syntax.cjs. Do not edit.\n// @ts-nocheck\n/*! PrismJS\n${license}\n*/\nexport function createDiffSyntax() {\n    'worklet';\n${result.outputFiles[0].text}\n    return DiffSyntax.tokenize;\n}\n`;
if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== code) {
        throw new Error('Diff syntax factory is stale. Run pnpm --filter happy-app generate:diff-syntax');
    }
} else {
    writeFileSync(output, code);
}
console.log(`Diff syntax factory: ${Buffer.byteLength(code)} bytes${process.argv.includes('--check') ? ' (verified)' : ''}`);