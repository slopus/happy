// Generate literal WebView code before Metro/Hermes erases function source.
// Run after changing mermaidRuntime.ts; --check rejects a stale artifact.
const { buildSync } = require('esbuild');
const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

function buildMermaidRuntimeSource() {
    const bundle = buildSync({
        entryPoints: [resolve(__dirname, '../sources/components/markdown/mermaidRuntime.ts')],
        bundle: true, write: false, format: 'iife', globalName: 'pawsMermaidRuntime',
        minify: true, target: 'es2017', legalComments: 'none',
    }).outputFiles[0].text;
    if (/<\/script/i.test(bundle)) throw new Error('Mermaid runtime must be safe inside an inline script');
    return bundle;
}

function generate() {
    const target = resolve(__dirname, '../sources/components/markdown/mermaidRuntimeSource.generated.ts');
    const text = '// Generated by scripts/generate-mermaid-runtime.cjs. Do not edit by hand.\n' +
        'export const MERMAID_RUNTIME_SOURCE = ' + JSON.stringify(buildMermaidRuntimeSource()) + ';\n';
    if (process.argv.includes('--check')) {
        if (readFileSync(target, 'utf8') !== text) throw new Error('Stale Mermaid runtime: run node scripts/generate-mermaid-runtime.cjs');
    } else {
        writeFileSync(target, text);
    }
}

module.exports = { buildMermaidRuntimeSource };
if (require.main === module) generate();
