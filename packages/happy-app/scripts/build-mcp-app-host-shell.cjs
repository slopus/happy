const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const packageRoot = path.resolve(__dirname, '..');
const entry = path.join(packageRoot, 'mcp-app-sandbox', 'hostShell.ts');
const output = path.join(packageRoot, 'sources', 'components', 'tools', 'mcpApps', 'generated', 'hostShellBundle.ts');
const serverOutput = path.resolve(
    packageRoot,
    '..',
    'happy-server',
    'sources',
    'app',
    'api',
    'generated',
    'mcpAppHostShellAssets.ts',
);

const built = esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    minify: true,
    platform: 'browser',
    format: 'iife',
    target: ['ios15', 'chrome100'],
    write: false,
    legalComments: 'none',
    sourcemap: false,
    charset: 'utf8',
});

const bundledJavascript = built.outputFiles[0].text;
const nativeJavascript = bundledJavascript.replaceAll('</script', '<\\/script');
const nativeHtml = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; frame-src data: blob: 'self'; img-src data: blob:; font-src data:; media-src 'none'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'"><meta http-equiv="Permissions-Policy" content="camera=(), microphone=(), geolocation=(), clipboard-read=(), clipboard-write=()"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}</style></head><body><script>${nativeJavascript}</script></body></html>`;
const source = `// Generated by scripts/build-mcp-app-host-shell.cjs. Do not edit.\nexport const MCP_APP_HOST_SHELL_HTML = ${JSON.stringify(nativeHtml)};\n`;

const proxyBootstrap = String.raw`"use strict";(()=>{
const MAX_BYTES=256*1024;
const exactOrigin=(raw)=>{try{if(!raw||raw.trim()!==raw||/[\s;'"\\?#]/u.test(raw))return null;const noRoot=raw.endsWith("/")?raw.slice(0,-1):raw,separator=noRoot.indexOf("://");if(separator<=0||noRoot.slice(separator+3).includes("/"))return null;const url=new URL(raw);if(url.username||url.password||url.pathname!=="/"||url.search||url.hash||!url.hostname||url.hostname.includes("*")||url.hostname.endsWith("."))return null;if(url.protocol!=="https:"){const match=/^http:\/\/(?:localhost|127\.0\.0\.1|\[::1\])(?::([1-9][0-9]{0,4}))?\/?$/u.exec(raw);if(!match||(match[1]!==void 0&&Number(match[1])>65535))return null}return url.origin==="null"?null:url.origin}catch{return null}};
const parentOrigin=exactOrigin(new URL(window.location.href).searchParams.get("parentOrigin"));
let referrerOrigin=null;try{referrerOrigin=new URL(document.referrer).origin}catch{}
if(!parentOrigin||referrerOrigin!==parentOrigin||window.parent===window)return;
let isolated=false;try{void window.top.location.href}catch{isolated=true}if(!isolated)return;
const parentWindow=window.parent;
const byteLength=(value)=>new TextEncoder().encode(value).byteLength;
window.addEventListener("message",(event)=>{if(event.source!==parentWindow||event.origin!==parentOrigin)return;event.stopImmediatePropagation();const data=typeof event.data==="string"&&byteLength(event.data)<=MAX_BYTES?event.data:"";window.dispatchEvent(new MessageEvent("message",{data,source:null}))},true);
Object.defineProperty(window,"ReactNativeWebView",{configurable:false,enumerable:false,writable:false,value:{postMessage(message){if(typeof message!=="string"||byteLength(message)>MAX_BYTES)return;parentWindow.postMessage(message,parentOrigin)}}});
parentWindow.postMessage(JSON.stringify({type:"sandbox-proxy-ready",parentOrigin}),parentOrigin);
})();
`;
const serverHtml = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}</style></head><body><script src="/mcp-app-sandbox/host.js" defer></script></body></html>';
const serverJavascript = `${proxyBootstrap}${bundledJavascript}`;
const serverSource = `// Generated by packages/happy-app/scripts/build-mcp-app-host-shell.cjs. Do not edit.\nexport const MCP_APP_SANDBOX_HOST_HTML = ${JSON.stringify(serverHtml)};\nexport const MCP_APP_SANDBOX_HOST_JAVASCRIPT = ${JSON.stringify(serverJavascript)};\n`;

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    const currentServer = fs.existsSync(serverOutput) ? fs.readFileSync(serverOutput, 'utf8') : '';
    if (current !== source || currentServer !== serverSource) {
        process.stderr.write('MCP App Host Shell bundle is out of date. Run build:mcp-app-host-shell.\n');
        process.exitCode = 1;
    }
} else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.mkdirSync(path.dirname(serverOutput), { recursive: true });
    fs.writeFileSync(output, source);
    fs.writeFileSync(serverOutput, serverSource);
}
