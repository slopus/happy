import { describe, expect, it } from 'vitest';
import type { ToolCall } from '@/sync/typesMessage';
import { readAgentRoleResult } from './agentRoleResult';
import { normalizeRawMessage, type NormalizedMessage } from '@/sync/typesRaw';
import { createReducer, reducer } from '@/sync/reducer/reducer';

const role = { id: 'writer-id', name: 'Technical writer', description: 'Write technical articles', agent: 'antigravity',
    model: 'gemini-neon', effort: 'high', autoDelegate: false, createdAt: 1, updatedAt: 2 };
const result = { success: true, role, roles: [role] };
const tool = (patch: Partial<ToolCall> = {}): ToolCall => ({ name: 'mcp__happy__agent_roles', state: 'completed',
    input: { action: 'create', role: { id: role.id } }, result,
    createdAt: 1, startedAt: 1, completedAt: 2, description: null, ...patch });

describe('readAgentRoleResult', () => {
    it.each([
        result,
        JSON.stringify(result),
        { content: [{ type: 'text', text: JSON.stringify(result) }], isError: false },
        JSON.stringify({ content: [{ type: 'text', text: JSON.stringify(result) }] }),
    ])('reads one valid saved-role receipt from the direct or MCP result', response => {
        expect(readAgentRoleResult(tool({ result: response }))).toEqual(role);
    });

    it('accepts an unprefixed update and an ID generated by the create tool', () => {
        expect(readAgentRoleResult(tool({ name: 'agent_roles', input: { action: 'update', roleId: role.id, patch: { name: role.name } } }))).toEqual(role);
        expect(readAgentRoleResult(tool({ input: { action: 'create', role: { name: role.name } } }))).toEqual(role);
    });

    it('reads the bounded saved receipt delivered by native Codex and ACP', () => {
        const mcpAppResult = { version: 1 as const, state: 'available' as const, content: [], structuredContent: { success: true, role } };
        expect(readAgentRoleResult(tool({ name: 'McpTool', input: { server: 'happy', tool: 'agent_roles', arguments: { action: 'create', role: { id: role.id } } }, result: null, mcpAppResult }))).toEqual(role);
        expect(readAgentRoleResult(tool({ result: null, mcpAppResult }))).toEqual(role);
        expect(readAgentRoleResult(tool({ result: null, mcpAppResult: { ...mcpAppResult, structuredContent: undefined, content: [{ type: 'text', text: JSON.stringify({ success: true, role }) }] } }))).toEqual(role);
        expect(readAgentRoleResult(tool({ name: 'McpTool', input: { server: 'other', tool: 'agent_roles', arguments: { action: 'create' } }, mcpAppResult }))).toBeNull();
        expect(readAgentRoleResult(tool({ result: null, mcpAppResult: { version: 1, state: 'unavailable', code: 'MCP_APP_RESULT_TOO_LARGE' } }))).toBeNull();
    });

    it.each(['codex', 'antigravity'])('preserves a native %s receipt through normalization and reduction', agent => {
        const envelopes = [{ id: 'role-start', time: 1000, role: 'agent', turn: 'role-turn', ev: {
            t: 'tool-call-start', call: 'role-call', name: agent === 'codex' ? 'McpTool' : 'mcp__happy__agent_roles',
            title: 'happy.agent_roles', description: 'Save role', args: agent === 'codex'
                ? { server: 'happy', tool: 'agent_roles', arguments: { action: 'update', roleId: role.id, patch: { name: role.name } } }
                : { action: 'update', roleId: role.id, patch: { name: role.name } },
        } }, { id: 'role-end', time: 1100, role: 'agent', turn: 'role-turn', ev: {
            t: 'tool-call-end', call: 'role-call', status: 'completed',
            mcpAppResult: { version: 1, state: 'available', content: [], structuredContent: { success: true, role } },
        } }];
        const messages = envelopes.map((content, i) => normalizeRawMessage(`role-db-${i}`, null, content.time,
            { role: 'session', content } as any)).filter((message): message is NormalizedMessage => message !== null);
        expect(messages).toHaveLength(2);
        const output = reducer(createReducer(), messages);
        const message = output.messages.find(message => message.kind === 'tool-call');
        expect(message?.kind).toBe('tool-call');
        if (message?.kind === 'tool-call') expect(readAgentRoleResult(message.tool)).toEqual(role);
    });

    it.each(['running', 'error', 'cancelled'] as const)('does not present a %s call as a saved result', state => {
        expect(readAgentRoleResult(tool({ state }))).toBeNull();
    });

    it.each(['list', 'delete', 'save'])('does not invent a saved result for %s', action => {
        expect(readAgentRoleResult(tool({ input: { action } }))).toBeNull();
    });

    it.each(['agent_roles_extra', 'my_agent_roles', 'Read', 'mcp__happy__delegate_task', 'mcp__other__agent_roles'])('does not reinterpret the tool %s', name => {
        expect(readAgentRoleResult(tool({ name }))).toBeNull();
    });

    it.each([
        { ...result, success: false },
        { ...result, role: { ...role, id: '../other' } },
        { success: true, roles: [role] },
        { isError: true, content: [{ type: 'text', text: JSON.stringify(result) }] },
        { content: [{ type: 'text', text: JSON.stringify(result) }, { type: 'text', text: 'another result' }] },
        { content: [{ type: 'text', text: 'Saved role writer-id' }] },
        { nested: result },
        `\`\`\`json\n${JSON.stringify(result)}\n\`\`\``,
        'x'.repeat(2 * 1024 * 1024 + 1),
    ])('rejects failed, malformed, ambiguous or prose-only results', response => {
        expect(readAgentRoleResult(tool({ result: response }))).toBeNull();
    });

    it('requires the actual returned ID to match the requested existing or preallocated ID', () => {
        expect(readAgentRoleResult(tool({ input: { action: 'update', roleId: 'another-id', patch: { name: role.name } } }))).toBeNull();
        expect(readAgentRoleResult(tool({ input: { action: 'update', patch: { name: role.name } } }))).toBeNull();
        expect(readAgentRoleResult(tool({ input: { action: 'create', role: { id: 'another-id' } } }))).toBeNull();
    });
});
