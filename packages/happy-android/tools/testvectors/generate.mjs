// Generates crypto/src/test/resources/happy-ts-vectors.json from happy-app's
// own TypeScript sources, so the Kotlin port is checked against the code it
// ports rather than against a re-implementation.
//
//   cd packages/happy-android/tools/testvectors && npm install && npm run generate
//
// Every function under test that consumes randomness is fed scripted bytes
// (see shims/random.mjs); the vectors record those bytes so the Kotlin tests
// can replay them and compare output byte for byte.

import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

register('./hooks.mjs', import.meta.url);

const { scriptRandom, assertRandomDrained, nextRandom } = await import('./shims/random.mjs');
const sodium = (await import('./shims/libsodium.lib.mjs')).default;

// aes.web.ts draws its IV from crypto.getRandomValues.
globalThis.crypto.getRandomValues = (array) => {
    array.set(nextRandom(array.length));
    return array;
};

const { encodeBase64, decodeBase64 } = await import('@/encryption/base64');
const { encodeHex } = await import('@/encryption/hex');
const { deriveKey, deriveSecretKeyTreeRoot, deriveSecretKeyTreeChild } = await import('@/encryption/deriveKey');
const { encryptBox, decryptBox, encryptSecretBox } = await import('@/encryption/libsodium');
const { encryptBlob } = await import('@/encryption/blob');
const { AES256Encryption, SecretBoxEncryption } = await import('@/sync/encryption/encryptor');
const { formatSecretKeyForBackup, parseBackupSecretKey, normalizeSecretKey } = await import('@/auth/secretKeyBackup');
const { authChallenge } = await import('@/auth/authChallenge');

const hex = (bytes) => encodeHex(bytes).toLowerCase();

// Deterministic, distinct byte strings: SHA-512 of a label, truncated.
function bytes(label, size) {
    const out = new Uint8Array(size);
    let block = 0;
    for (let offset = 0; offset < size; offset += 64) {
        const digest = createHash('sha512').update(`${label}#${block++}`).digest();
        out.set(digest.subarray(0, Math.min(64, size - offset)), offset);
    }
    return out;
}

const vectors = {
    _comment: 'Generated by tools/testvectors/generate.mjs from packages/happy-app sources. Do not edit by hand.',
};

//
// base64.ts
//

vectors.base64 = [
    new Uint8Array([]),
    new Uint8Array([72]),
    new Uint8Array([251, 255]),
    new Uint8Array([62, 63, 62, 63]),
    new Uint8Array([252, 253, 254, 255]),
    bytes('base64', 32),
    bytes('base64-long', 100),
].map((data) => ({
    dataHex: hex(data),
    standard: encodeBase64(data),
    url: encodeBase64(data, 'base64url'),
}));

//
// deriveKey.ts
//

vectors.deriveKey = [
    { seed: new TextEncoder().encode('test seed'), usage: 'test usage', path: ['child1', 'child2'] },
    { seed: bytes('master', 32), usage: 'Happy EnCoder', path: ['content'] },
    { seed: bytes('master', 32), usage: 'Happy Coder', path: ['analytics', 'id'] },
    { seed: bytes('data-key', 32), usage: 'Happy Blobs', path: ['session'] },
    { seed: bytes('unicode', 32), usage: 'Usage ✓', path: ['päth', '路径', ''] },
    { seed: bytes('empty', 32), usage: 'Root only', path: [] },
];
for (const vector of vectors.deriveKey) {
    const root = await deriveSecretKeyTreeRoot(vector.seed, vector.usage);
    const children = [];
    let chainCode = root.chainCode;
    for (const index of vector.path) {
        const child = await deriveSecretKeyTreeChild(chainCode, index);
        children.push({ keyHex: hex(child.key), chainCodeHex: hex(child.chainCode) });
        chainCode = child.chainCode;
    }
    Object.assign(vector, {
        seed: undefined,
        seedHex: hex(vector.seed),
        rootKeyHex: hex(root.key),
        rootChainCodeHex: hex(root.chainCode),
        children,
        keyHex: hex(await deriveKey(vector.seed, vector.usage, vector.path)),
    });
}

//
// libsodium primitives, through the same library object happy-app uses.
//

vectors.sign = [bytes('sign-seed-1', 32), bytes('sign-seed-2', 32)].map((seed, i) => {
    const keypair = sodium.crypto_sign_seed_keypair(seed);
    const message = i === 0 ? new Uint8Array([]) : bytes('sign-message', 77);
    return {
        seedHex: hex(seed),
        publicKeyHex: hex(keypair.publicKey),
        secretKeyHex: hex(keypair.privateKey),
        messageHex: hex(message),
        signatureHex: hex(sodium.crypto_sign_detached(message, keypair.privateKey)),
    };
});

vectors.boxSeedKeypair = [bytes('box-seed-1', 32), bytes('box-seed-2', 32), new Uint8Array(32)].map((seed) => {
    const keypair = sodium.crypto_box_seed_keypair(seed);
    return { seedHex: hex(seed), publicKeyHex: hex(keypair.publicKey), secretKeyHex: hex(keypair.privateKey) };
});

vectors.boxBeforeNm = [1, 2].map((i) => {
    const a = sodium.crypto_box_seed_keypair(bytes(`beforenm-a-${i}`, 32));
    const b = sodium.crypto_box_seed_keypair(bytes(`beforenm-b-${i}`, 32));
    return {
        publicKeyHex: hex(b.publicKey),
        secretKeyHex: hex(a.privateKey),
        sharedKeyHex: hex(sodium.crypto_box_beforenm(b.publicKey, a.privateKey)),
    };
});

vectors.secretbox = [0, 1, 31, 32, 33, 64, 65, 1000].map((length) => {
    const key = bytes(`secretbox-key-${length}`, 32);
    const nonce = bytes(`secretbox-nonce-${length}`, 24);
    const message = bytes(`secretbox-message-${length}`, length);
    return {
        keyHex: hex(key),
        nonceHex: hex(nonce),
        messageHex: hex(message),
        ciphertextHex: hex(sodium.crypto_secretbox_easy(message, nonce, key)),
    };
});

//
// libsodium.ts / blob.ts bundles
//

vectors.encryptBox = [0, 32, 200].map((length) => {
    const recipient = sodium.crypto_box_seed_keypair(bytes(`box-recipient-${length}`, 32));
    const ephemeralSecretKey = bytes(`box-ephemeral-${length}`, 32);
    const nonce = bytes(`box-nonce-${length}`, 24);
    const data = bytes(`box-data-${length}`, length);
    scriptRandom(ephemeralSecretKey, nonce);
    const bundle = encryptBox(data, recipient.publicKey);
    assertRandomDrained();
    if (hex(decryptBox(bundle, recipient.privateKey)) !== hex(data)) throw new Error('encryptBox round trip failed');
    return {
        recipientPublicKeyHex: hex(recipient.publicKey),
        recipientSecretKeyHex: hex(recipient.privateKey),
        ephemeralSecretKeyHex: hex(ephemeralSecretKey),
        nonceHex: hex(nonce),
        dataHex: hex(data),
        bundleHex: hex(bundle),
    };
});

vectors.encryptBlob = [0, 5, 4096].map((length) => {
    const key = bytes(`blob-key-${length}`, 32);
    const nonce = bytes(`blob-nonce-${length}`, 24);
    const data = bytes(`blob-data-${length}`, length);
    scriptRandom(nonce);
    const bundle = encryptBlob(data, key);
    assertRandomDrained();
    return { keyHex: hex(key), nonceHex: hex(nonce), dataHex: hex(data), bundleHex: hex(bundle) };
});

//
// encryptor.ts: JSON payload ciphers
//

const payloads = [
    { hello: 'world' },
    { schemaVersion: 2, viewInline: false, recentMachinePaths: [], lastUsedAgent: null, avatarStyle: 'brutalist' },
    { role: 'session', content: { id: 'msg_01', time: 1739347230000, role: 'agent', ev: { t: 'text', text: 'Hello, 世界! 🌍 "quoted" \\ back\nslash' } } },
    'just a string',
    [1, 2, 3, true, null],
];

vectors.aes256 = [];
for (const [i, payload] of payloads.entries()) {
    const key = bytes(`aes-key-${i}`, 32);
    const iv = bytes(`aes-iv-${i}`, 12);
    scriptRandom(iv);
    const [bundle] = await new AES256Encryption(key).encrypt([payload]);
    assertRandomDrained();
    const [decrypted] = await new AES256Encryption(key).decrypt([bundle]);
    if (JSON.stringify(decrypted) !== JSON.stringify(payload)) throw new Error('AES round trip failed');
    vectors.aes256.push({ keyHex: hex(key), ivHex: hex(iv), json: JSON.stringify(payload), bundleBase64: encodeBase64(bundle) });
}

vectors.secretBoxJson = [];
for (const [i, payload] of payloads.entries()) {
    const secret = bytes(`secretbox-json-key-${i}`, 32);
    const nonce = bytes(`secretbox-json-nonce-${i}`, 24);
    scriptRandom(nonce);
    const [bundle] = await new SecretBoxEncryption(secret).encrypt([payload]);
    assertRandomDrained();
    // libsodium.ts encryptSecretBox is the same function the class delegates to.
    scriptRandom(nonce);
    if (hex(encryptSecretBox(payload, secret)) !== hex(bundle)) throw new Error('encryptSecretBox mismatch');
    assertRandomDrained();
    vectors.secretBoxJson.push({ secretHex: hex(secret), nonceHex: hex(nonce), json: JSON.stringify(payload), bundleBase64: encodeBase64(bundle) });
}

//
// sync/encryption/encryption.ts (Encryption.create and the data-key wrap).
// That module pulls in the whole sync store, so its few lines are restated
// here on top of the real deriveKey / encodeHex / encryptBox / decryptBox.
//

vectors.accountEncryption = [];
for (const i of [1, 2]) {
    const masterSecret = bytes(`account-master-${i}`, 32);
    const contentDataKey = await deriveKey(masterSecret, 'Happy EnCoder', ['content']);
    const contentKeyPair = sodium.crypto_box_seed_keypair(contentDataKey);
    const anonId = encodeHex(await deriveKey(masterSecret, 'Happy Coder', ['analytics', 'id'])).slice(0, 16).toLowerCase();
    const providerAccountKey = await deriveKey(masterSecret, 'Happy Coder', ['analytics', 'provider-account']);

    // encryptEncryptionKey
    const dataKey = bytes(`account-data-key-${i}`, 32);
    const ephemeralSecretKey = bytes(`account-ephemeral-${i}`, 32);
    const nonce = bytes(`account-nonce-${i}`, 24);
    scriptRandom(ephemeralSecretKey, nonce);
    const encrypted = encryptBox(dataKey, contentKeyPair.publicKey);
    assertRandomDrained();
    const wrapped = new Uint8Array(encrypted.length + 1);
    wrapped[0] = 0;
    wrapped.set(encrypted, 1);

    // decryptEncryptionKey
    const unwrapped = decryptBox(decodeBase64(encodeBase64(wrapped)).slice(1), contentKeyPair.privateKey);
    if (hex(unwrapped) !== hex(dataKey)) throw new Error('data key unwrap failed');

    vectors.accountEncryption.push({
        masterSecretHex: hex(masterSecret),
        contentPublicKeyHex: hex(contentKeyPair.publicKey),
        anonId,
        providerAccountKeyHex: hex(providerAccountKey),
        dataKeyHex: hex(dataKey),
        ephemeralSecretKeyHex: hex(ephemeralSecretKey),
        nonceHex: hex(nonce),
        wrappedDataKeyBase64: encodeBase64(wrapped),
        blobKeyHex: hex(await deriveKey(dataKey, 'Happy Blobs', ['session'])),
        masterBlobKeyHex: hex(await deriveKey(masterSecret, 'Happy Blobs', ['master'])),
    });
}

//
// auth/
//

vectors.authChallenge = [1, 2].map((i) => {
    const secret = bytes(`auth-secret-${i}`, 32);
    const challengeBytes = bytes(`auth-challenge-${i}`, 32);
    scriptRandom(challengeBytes);
    const { challenge, signature, publicKey } = authChallenge(secret);
    assertRandomDrained();
    return {
        secretHex: hex(secret),
        challengeHex: hex(challenge),
        signatureHex: hex(signature),
        publicKeyHex: hex(publicKey),
        requestBody: { challenge: encodeBase64(challenge), signature: encodeBase64(signature), publicKey: encodeBase64(publicKey) },
    };
});

// authQRStart.ts generateAuthKeyPair + the restore screen's QR text. That
// module imports axios and the server config, so its two lines are restated.
vectors.accountLink = [1, 2].map((i) => {
    const seed = bytes(`account-link-seed-${i}`, 32);
    const keypair = sodium.crypto_box_seed_keypair(seed);
    return {
        seedHex: hex(seed),
        publicKeyHex: hex(keypair.publicKey),
        secretKeyHex: hex(keypair.privateKey),
        url: 'happy:///account?' + encodeBase64(keypair.publicKey, 'base64url'),
    };
});

vectors.secretKeyBackup = [
    Uint8Array.from({ length: 32 }, (_, i) => i),
    new Uint8Array(32).fill(255),
    new Uint8Array(32),
    Uint8Array.from({ length: 32 }, (_, i) => (i * 7 + 13) % 256),
    bytes('backup', 32),
].map((secret) => {
    const base64url = encodeBase64(secret, 'base64url');
    const formatted = formatSecretKeyForBackup(base64url);
    if (parseBackupSecretKey(formatted) !== base64url) throw new Error('backup round trip failed');
    const messy = ` "${formatted.toLowerCase().replace(/O/gi, '0').replace(/-/g, ' . ')}"\n`;
    return { base64url, formatted, messy, normalizedMessy: normalizeSecretKey(messy) };
});

const output = new URL('../../crypto/src/test/resources/happy-ts-vectors.json', import.meta.url);
writeFileSync(output, JSON.stringify(vectors, null, 2) + '\n');
console.log(`Wrote ${output.pathname}`);
