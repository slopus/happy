// Generates app/src/test/resources/happy-ts-send-vectors.json by running
// happy-app's own `Sync.sendMessage` (sources/sync/sync.ts), so the Kotlin
// sender is checked against the code it ports, byte for byte.
//
//   cd packages/happy-android/tools/testvectors && npm install && npm run generate:send
//
// sync.ts imports the whole app shell, so only the method itself is taken
// from the file: its text is cut out of the class, the types are stripped
// with Node's own TypeScript support, and it runs against stand-ins for
// the store, the platform and the outbox. The record encryption is the
// real AES256Encryption with a scripted IV, as in generate.mjs.

import { register, stripTypeScriptTypes } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

register('./hooks.mjs', import.meta.url);

const { scriptRandom, assertRandomDrained, nextRandom } = await import('./shims/random.mjs');
await import('./shims/libsodium.lib.mjs');

globalThis.crypto.getRandomValues = (array) => {
    array.set(nextRandom(array.length));
    return array;
};

const { encodeBase64 } = await import('@/encryption/base64');
const { encodeHex } = await import('@/encryption/hex');
const { AES256Encryption } = await import('@/sync/encryption/encryptor');
const { systemPrompt } = await import('@/sync/prompt/systemPrompt');
const { isRigMetadataV1, rigCanUseAttachments } = await import('@/sync/rig');

const hex = (bytes) => encodeHex(bytes).toLowerCase();

function bytes(label, size) {
    const out = new Uint8Array(size);
    let block = 0;
    for (let offset = 0; offset < size; offset += 64) {
        const digest = createHash('sha512').update(`${label}#${block++}`).digest();
        out.set(digest.subarray(0, Math.min(64, size - offset)), offset);
    }
    return out;
}

// Cut `async sendMessage(...) { ... }` out of the Sync class.
const source = readFileSync(new URL('../../../happy-app/sources/sync/sync.ts', import.meta.url), 'utf8');
const start = source.indexOf('    async sendMessage(sessionId: string, text: string');
if (start < 0) throw new Error('sendMessage not found in sync.ts');
let depth = 0;
let end = -1;
for (let index = source.indexOf('{', source.indexOf(')', start)); index < source.length; index++) {
    if (source[index] === '{') depth++;
    if (source[index] === '}' && --depth === 0) { end = index + 1; break; }
}
const method = source.slice(start, end);
// Brace counting must land exactly on the method's end, before the next member.
if (!/^\s*\/\*\* Server sent us settings/.test(source.slice(end))) throw new Error('sendMessage was not cut cleanly');

const javascript = stripTypeScriptTypes(`class Sync {\n${method}\n}`, { mode: 'strip' });

const vectors = {
    _comment: 'Generated by tools/testvectors/send.mjs from packages/happy-app/sources/sync/sync.ts. Do not edit by hand.',
    systemPrompt,
    cases: [],
};

const cases = [
    { name: 'plain text', text: 'Hello', options: undefined, modeMeta: {}, deliveryMeta: {} },
    {
        name: 'every mode field and a display text',
        text: '/review the diff',
        options: { displayText: 'Review' },
        modeMeta: { permissionMode: 'acceptEdits', model: 'opus', modelProviderId: 'claude', effort: 'high', serviceTier: 'fast' },
        deliveryMeta: {},
    },
    {
        name: 'default model and effort as null, with receipts',
        text: 'go',
        options: { source: 'chat' },
        modeMeta: { permissionMode: 'default', model: null, effort: null },
        deliveryMeta: { expectsAcceptance: true, queuedWhileBusy: false },
    },
    {
        name: 'queued behind a busy turn, service tier null',
        text: 'next',
        options: undefined,
        modeMeta: { permissionMode: 'read_only', model: 'shared-model', modelProviderId: 'claude', effort: 'low', serviceTier: null },
        deliveryMeta: { expectsAcceptance: true, queuedWhileBusy: true },
    },
    {
        name: 'an empty display text is left out',
        text: 'Hello, 世界! 🌍 "quoted" \\ back\nslash\ttab \u2028 \u0007',
        options: { displayText: '' },
        modeMeta: { effort: 'max' },
        deliveryMeta: {},
    },
];

for (const [i, vector] of cases.entries()) {
    const key = bytes(`send-key-${i}`, 32);
    const iv = bytes(`send-iv-${i}`, 12);
    const localId = `local-${i}`;
    let record = null;
    const encryptor = new AES256Encryption(key);
    const session = { id: 'session-1', metadata: { path: '/repo', host: 'mac', flavor: 'claude' }, draft: null };
    const state = {
        sessions: { 'session-1': session },
        sessionMessages: {},
        settings: {},
        markSessionMessageSent() {},
    };

    const Sync = new Function(
        'storage', 'Modal', 't', 'resolveMessageModeMeta', 'UnsupportedPermissionModeError', 'resolveMessageDeliveryMeta',
        'isRigMetadataV1', 'rigCanUseAttachments', 'getImageAttachmentSendPlan', 'isAttachmentAllowedByPolicy',
        'randomUUID', 'normalizeRawMessage', 'Platform', 'isRunningOnMac', 'systemPrompt', 'releaseSpawnedSession',
        'rigComposerClear', 'trackMessageSent',
        `${javascript}\nreturn Sync;`,
    )(
        { getState: () => state },
        { alert() { throw new Error('unexpected alert'); } },
        (key) => key,
        () => vector.modeMeta,
        class UnsupportedPermissionModeError extends Error {},
        () => vector.deliveryMeta,
        isRigMetadataV1,
        rigCanUseAttachments,
        () => ({ shouldUseAttachments: false, shouldShowUnsupportedAlert: false, shouldSendText: true }),
        () => true,
        () => localId,
        () => null,
        { OS: 'android' },
        () => false,
        systemPrompt,
        () => {},
        () => { throw new Error('unexpected draft clear'); },
        () => {},
    );
    const sync = new Sync();
    // One object per session: sendMessage checks the key did not change while it encrypted.
    const sessionEncryption = {
        async encryptRawRecord(data) {
            record = JSON.stringify(data);
            const [bundle] = await encryptor.encrypt([data]);
            return encodeBase64(bundle, 'base64');
        },
    };
    const encryption = { getSessionEncryption: () => sessionEncryption };
    Object.assign(sync, {
        encryption,
        pendingOutbox: new Map(),
        async ensureSessionReady() {},
        enqueueMessages() {},
        getSendSync: () => ({ invalidate() {}, async invalidateAndAwait() {} }),
        maybeStartBackgroundSendWatchdog() {},
    });

    scriptRandom(iv);
    const accepted = await sync.sendMessage('session-1', vector.text, vector.options);
    assertRandomDrained();
    if (accepted !== true) throw new Error(`case ${vector.name} was not accepted`);
    const [outbox] = sync.pendingOutbox.get('session-1');
    if (outbox.localId !== localId || outbox.kind !== 'user') throw new Error('unexpected outbox entry');

    vectors.cases.push({
        name: vector.name,
        text: vector.text,
        options: vector.options ?? null,
        modeMeta: vector.modeMeta,
        deliveryMeta: vector.deliveryMeta,
        keyHex: hex(key),
        ivHex: hex(iv),
        localId,
        recordJson: record,
        contentBase64: outbox.content,
    });
}

const output = new URL('../../app/src/test/resources/happy-ts-send-vectors.json', import.meta.url);
writeFileSync(output, JSON.stringify(vectors, null, 2) + '\n');
console.log(`Wrote ${output.pathname}`);
