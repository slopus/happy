#!/usr/bin/env python3
"""Writes GenUiTheme.kt from the shared Gen UI theme.json (copied here from the spec).

    python3 tools/genui/theme.py

GenUiThemeTest checks the generated file still matches theme.json.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '../../app/src/main/kotlin/com/slopus/happy/genui/GenUiTheme.kt')
theme = json.load(open(os.path.join(HERE, 'theme.json')))

def argb(hex_):
    h = hex_.lstrip('#')
    rgb, a = h[:6], (h[6:8] if len(h) == 8 else 'FF')
    return f'Color(0x{a.upper()}{rgb.upper()})'

# Semantic tones first, then the raw colours: a document may name either wherever it takes a tone.
inks = {**theme['tones'], **theme['colors']}

def colours(side):
    chart = theme['chart']
    t = lambda key: '\n'.join(f'                Tone.{n.capitalize()} to {argb(v[key][side])},' for n, v in inks.items())
    palette = ', '.join(argb(c[side]) for c in chart['palette'])
    return f'''GenUiColors(
            ink = mapOf(
{t('ink')}
            ),
            text = mapOf(
{t('text')}
            ),
            fill = mapOf(
{t('fill')}
            ),
            palette = listOf({palette}),
            muted = {argb(chart['muted'][side])},
            grid = {argb(chart['grid'][side])},
            axisLabel = {argb(chart['axisLabel'][side])},
        )'''

markers = '\n'.join(f'    StepStatus.{k.capitalize()} to Tone.{v.capitalize()},' for k, v in theme['markers'].items())

open(OUT, 'w').write(f'''package com.slopus.happy.genui

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

// Generated by tools/genui/theme.py from tools/genui/theme.json (the Gen UI
// spec's shared colours); do not edit by hand. Surfaces, body text and
// hairlines are not here: they come from the app theme.

/**
 * What a document may colour with: the semantic tones, then the theme's raw
 * colours. An unknown name is [Neutral].
 */
enum class Tone {{ {', '.join(n.capitalize() for n in inks)} }}

/** The tone of each step marker's status. */
val GenUiMarkers: Map<StepStatus, Tone> = mapOf(
{markers}
)

/** The colours every Gen UI client shares: the inks and fills of each [Tone], and the chart's. */
@Immutable
data class GenUiColors(
    val ink: Map<Tone, Color>,
    val text: Map<Tone, Color>,
    val fill: Map<Tone, Color>,
    val palette: List<Color>,
    val muted: Color,
    val grid: Color,
    val axisLabel: Color,
) {{
    /** Icons, bars, sparklines, markers and chart marks of [tone]. */
    fun ink(tone: Tone): Color = ink.getValue(tone)

    /** Text of [tone], a pill's label included: the ink at 4.5:1 on the card. */
    fun text(tone: Tone): Color = text.getValue(tone)

    /** The background of a pill or notice of [tone]. */
    fun fill(tone: Tone): Color = fill.getValue(tone)

    /** A plot colour: `palette[(N - 1) % size]`, a named colour's ink, or [muted]. */
    fun plot(color: PlotColor): Color =
        color.index?.let {{ palette[Math.floorMod(it - 1, palette.size)] }} ?: color.tone?.let(::ink) ?: muted

    companion object {{
        val Light = {colours('light')}

        val Dark = {colours('dark')}
    }}
}}
''')
