#!/usr/bin/env node
// Generate native Swift catalogs and test vectors from plain JSON.
// Run: node packages/happy-ios/scripts/generate-translations.mjs
import { writeFileSync } from 'node:fs';
import { languages, parameters, readCatalog, render } from '../../happy-i18n/catalogs.mjs';

const vectorCounts = [0, 1, 2, 3, 4, 5, 11, 12, 14, 21, 22, 25, 101, 111, 112, 1000, 1001, 1002];

function sampleArgs(types) {
    const base = {};
    for (const [name, kind] of Object.entries(types)) {
        if (kind === 'text') base[name] = `Text ${name} «β»`;
        else if (kind === 'number') base[name] = 42;
        else if (kind === 'bool') base[name] = true;
        else base[name] = kind.values[0];
    }
    const cases = [base];
    for (const [name, kind] of Object.entries(types)) {
        if (kind === 'number') for (const value of vectorCounts) cases.push({ ...base, [name]: value });
        else if (kind === 'bool') cases.push({ ...base, [name]: false });
        else if (typeof kind === 'object') for (const value of kind.values.slice(1)) cases.push({ ...base, [name]: value });
    }
    return cases;
}

let swift = `// Generated by scripts/generate-translations.mjs from
// packages/happy-i18n/translations. Do not edit.

extension TranslationCatalog {
    /// Every catalog's JSON, by language code.
    static let sources: [(code: String, json: String)] = [
`;
const vectors = {};
let englishKeys;
for (const code of languages) {
    const { entries } = readCatalog(code);
    const keys = Object.keys(entries).sort();
    englishKeys ??= keys;
    if (JSON.stringify(keys) !== JSON.stringify(englishKeys)) throw new Error(`${code}: keys differ from English`);
    const json = JSON.stringify(Object.fromEntries(keys.map(key => [key, entries[key]])));
    if (json.includes('"####')) throw new Error('Raw string delimiter in catalog');
    swift += `        (${JSON.stringify(code)}, ####"${json}"####),\n`;
    vectors[code] = [];
    for (const [key, entry] of Object.entries(entries)) {
        if (typeof entry === 'string') continue;
        const types = parameters[key.split('.').at(-1)];
        if (!types) throw new Error(`Missing parameters for ${key}`);
        for (const args of sampleArgs(types)) vectors[code].push({ key, args, output: render(entry, args) });
    }
    console.log(`${code}: ${keys.length} keys, ${vectors[code].length} vectors`);
}
swift += `    ]
}
`;
writeFileSync(new URL('../Sources/HappyCore/Localization/TranslationCatalogs.swift', import.meta.url), swift);
const lines = Object.entries(vectors).map(([code, list]) => `${JSON.stringify(code)}:${JSON.stringify(list)}`);
writeFileSync(new URL('../Tests/HappyCoreTests/Fixtures/translation-vectors.json', import.meta.url), `{\n${lines.join(',\n')}\n}\n`);