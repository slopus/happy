#!/usr/bin/env node
// Writes Sources/HappyLayout/AvatarShaderTable.swift: what the live shader
// needs to draw each of the 200 avatar placeholders (its effect, colours,
// layout, angle and phase), worked out by @craftedstudios/shaders' own
// `resolve` and `angleOf` for the seed and effect the picture was made with
// (AvatarPlaceholders/AVATAR-PLACEHOLDERS-NOTICE.md). At its phase the shader
// draws the picture's frame; the clock moves it on from there.
//
// Needs the package installed where it is run from:
//
//   npm i --no-save @craftedstudios/shaders@1.0.1
//   node <path>/scripts/generate-avatar-shader-table.mjs
//
// @craftedstudios/shaders is MIT, Copyright (c) 2026 Crafted Studios; its
// notice travels with the pictures (AvatarPlaceholders/LICENSE-craftedstudios-shaders.txt).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = new URL('..', import.meta.url).pathname;
const notice = readFileSync(join(root, 'Sources/HappyUI/Resources/AvatarPlaceholders/AVATAR-PLACEHOLDERS-NOTICE.md'), 'utf8');
const wall = [...notice.matchAll(/^\| `avatar-placeholder-(\d{3})\.webp` \| `([^`]+)` \| (\w+) \|$/gm)].map(([, number, seed, effect]) => ({ number: Number(number), seed, effect }));
if (wall.length !== 200 || wall.some((entry, index) => entry.number !== index + 1)) throw new Error(`The notice lists ${wall.length} pictures, not 200 in order`);

const pkg = dirname(createRequire(join(process.cwd(), 'noop.js')).resolve('@craftedstudios/shaders/package.json'));
const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
const { resolve } = await import(pathToFileURL(join(pkg, 'src/options.js')));
const { angleOf } = await import(pathToFileURL(join(pkg, 'src/renderer.js')));
const { shaderColors } = await import(pathToFileURL(join(pkg, 'src/color.js')));

const number = (value) => {
  const text = Number(value).toFixed(6).replace(/0+$/, '').replace(/\.$/, '.0');
  return text === '-0.0' ? '0.0' : text;
};
const vector = (values) => `SIMD${values.length}(${values.map(number).join(', ')})`;

// The size the pictures were made at: 40 and up keeps all four colours.
const rows = wall.map(({ seed, effect }) => {
  const o = resolve({ seed, effect, size: 1024, interaction: 'none', motion: 'still' });
  const colors = shaderColors(o.palette).map(vector).join(', ');
  return `        .init(effect: .${o.traits.effect}, colors: [${colors}], layout: ${vector(o.traits.layout)}, angle: ${number(angleOf(o.traits))}, phase: ${number(o.traits.phase)}),`;
});

const out = `// Generated by scripts/generate-avatar-shader-table.mjs from
// @craftedstudios/shaders ${version} (MIT, Copyright (c) 2026 Crafted Studios).
// Do not edit.

extension AvatarShader {
    /// Each placeholder's drawing, in the pictures' order.
    static let table: [Parameters] = [
${rows.join('\n')}
    ]
}
`;
writeFileSync(join(root, 'Sources/HappyLayout/AvatarShaderTable.swift'), out);
console.log(`${rows.length} placeholders from @craftedstudios/shaders ${version}`);
