import Foundation

/// A value a catalog function is called with: text it interpolates, or a
/// number, flag or name that can also choose its words.
public enum TranslationValue: Sendable, Hashable, ExpressibleByStringLiteral, ExpressibleByIntegerLiteral, ExpressibleByBooleanLiteral {
    case text(String)
    case number(Int)
    case flag(Bool)

    public init(stringLiteral value: String) { self = .text(value) }
    public init(integerLiteral value: Int) { self = .number(value) }
    public init(booleanLiteral value: Bool) { self = .flag(value) }

    /// JavaScript's `${value}`.
    var interpolated: String {
        switch self {
        case .text(let text): text
        case .number(let number): String(number)
        case .flag(let flag): flag ? "true" : "false"
        }
    }
}

/// One of happy-app's UI catalogs (sources/text) and its `t(key, params)`,
/// generated by scripts/generate-translations.mjs. Immutable and decoded
/// once per language, so any thread can read it.
public final class TranslationCatalog: Sendable {
    /// Each catalog's own `plural` helper.
    enum PluralRule: Sendable {
        /// `count === 1 ? singular : plural`.
        case oneOther
        /// Russian: one (…1 but not …11), few (…2-4 but not …12-14), many.
        case russian
        /// Polish: one (exactly 1), few (…2-4 but not …12-14), many.
        case polish

        func category(_ value: Int) -> String {
            let n = abs(value), n10 = n % 10, n100 = n % 100
            switch self {
            case .oneOther:
                return value == 1 ? "one" : "other"
            case .russian:
                if n10 == 1 && n100 != 11 { return "one" }
                if (2...4).contains(n10) && (n100 < 10 || n100 >= 20) { return "few" }
                return "many"
            case .polish:
                if n == 1 { return "one" }
                if (2...4).contains(n10) && (n100 < 12 || n100 > 14) { return "few" }
                return "many"
            }
        }
    }

    struct Template: Sendable, Equatable {
        enum Part: Sendable, Equatable {
            case literal(String)
            case parameter(String)
        }

        var parts: [Part]

        /// `${name}` marks a parameter.
        init(_ text: String) {
            var parts: [Part] = []
            var rest = Substring(text)
            while let open = rest.range(of: "${"), let close = rest[open.upperBound...].firstIndex(of: "}") {
                if open.lowerBound > rest.startIndex { parts.append(.literal(String(rest[..<open.lowerBound]))) }
                parts.append(.parameter(String(rest[open.upperBound..<close])))
                rest = rest[rest.index(after: close)...]
            }
            if !rest.isEmpty { parts.append(.literal(String(rest))) }
            self.parts = parts
        }

        func render(_ values: [String: TranslationValue]) -> String {
            var text = ""
            for part in parts {
                switch part {
                case .literal(let literal): text += literal
                // JavaScript interpolates a missing parameter as "undefined".
                case .parameter(let name): text += values[name]?.interpolated ?? "undefined"
                }
            }
            return text
        }
    }

    enum Entry: Sendable {
        case text(String)
        case template(Template)
        /// The words chosen by one parameter: a plural category (or an exact
        /// number the catalog spells out), `true`/`false`, or a name.
        case choice(parameter: String, rule: PluralRule?, cases: [String: Template], exact: [Int: Template])
    }

    public let language: String
    private let entries: [String: Entry]
    private let fallback: TranslationCatalog?

    init(language: String, json: String, fallback: TranslationCatalog?) {
        self.language = language
        self.fallback = fallback
        let object = (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [String: Any] ?? [:]
        var entries: [String: Entry] = [:]
        entries.reserveCapacity(object.count)
        for (key, value) in object {
            if let text = value as? String {
                entries[key] = .text(text)
            } else if let entry = value as? [String: Any] {
                if let text = entry["t"] as? String {
                    entries[key] = .template(Template(text))
                } else if let parameter = entry["p"] as? String, let cases = entry["c"] as? [String: String] {
                    let rule: PluralRule? = switch entry["k"] as? String {
                    case "plural": .oneOther
                    case "plural-ru": .russian
                    case "plural-pl": .polish
                    default: nil
                    }
                    let exact = (entry["x"] as? [String: String] ?? [:]).reduce(into: [Int: Template]()) { result, item in
                        if let number = Int(item.key) { result[number] = Template(item.value) }
                    }
                    entries[key] = .choice(parameter: parameter, rule: rule, cases: cases.mapValues(Template.init), exact: exact)
                }
            }
        }
        self.entries = entries
    }

    /// The catalog for a language code from `AppLanguage.supported`;
    /// English for any other.
    public static func catalog(for language: String) -> TranslationCatalog {
        cache.catalog(language)
    }

    public static var english: TranslationCatalog { catalog(for: "en") }

    /// `t(key)` and `t(key, params)`: the language's words, English's when a
    /// key is missing, and the key itself when English lacks it too, as
    /// text/index.ts answers.
    public func callAsFunction(_ key: String, _ values: [String: TranslationValue] = [:]) -> String {
        guard let entry = entries[key] else {
            return fallback?(key, values) ?? key
        }
        switch entry {
        case .text(let text):
            return text
        case .template(let template):
            return template.render(values)
        case .choice(let parameter, let rule, let cases, let exact):
            let value = values[parameter]
            let template: Template?
            switch (value, rule) {
            case (.number(let number)?, let rule?):
                template = exact[number] ?? cases[rule.category(number)]
            case (.flag(let flag)?, nil):
                template = cases[flag ? "true" : "false"]
            case (.text(let name)?, nil):
                template = cases[name]
            default:
                template = nil
            }
            return template?.render(values) ?? key
        }
    }

    /// Whether the catalog has `key`, for the getters' tests.
    public func contains(_ key: String) -> Bool {
        entries[key] != nil
    }

    var keys: Dictionary<String, Entry>.Keys { entries.keys }

    private static let cache = Cache()

    /// Each language decoded on first use, once.
    private final class Cache: @unchecked Sendable {
        private let lock = NSLock()
        private var catalogs: [String: TranslationCatalog] = [:]

        func catalog(_ language: String) -> TranslationCatalog {
            let code = TranslationCatalog.sources.contains { $0.code == language } ? language : "en"
            if let cached = lock.withLock({ catalogs[code] }) { return cached }
            let english = code == "en" ? nil : catalog("en")
            let json = TranslationCatalog.sources.first { $0.code == code }?.json ?? "{}"
            // Decoded outside the lock; a race decodes twice and keeps one.
            let made = TranslationCatalog(language: code, json: json, fallback: english)
            return lock.withLock {
                if let cached = catalogs[code] { return cached }
                catalogs[code] = made
                return made
            }
        }
    }
}
